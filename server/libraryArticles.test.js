import test from "node:test";
import assert from "node:assert/strict";
import { build } from "esbuild";
import { readFileSync } from "node:fs";
const bundled = await build({ entryPoints: ["src/lib/libraryArticles.js"], bundle: true, write: false, format: "esm", platform: "node", plugins: [{name:"mock-cloud",setup(b){b.onResolve({filter:/supabaseClient/},()=>({path:"cloud",namespace:"mock"}));b.onLoad({filter:/.*/,namespace:"mock"},()=>({contents:"export const supabase=null;"}));}}] });
const { mergeLibraryArticleUpdate, validateLibraryArticle } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);
test("manual articles validate text and safe links without fetching a website",()=>{
 const valid={source_url:"https://example.com/read",title:" Read ",body_en:"First.\n\nSecond."};
 assert.equal(validateLibraryArticle(valid).title,"Read");
 assert.deepEqual(validateLibraryArticle(valid).analysis,{});
 for(const changes of [{source_url:"javascript:alert(1)"},{title:""},{body_en:" "},{analysis:[]},{analysis:null},{body_en:"x".repeat(50001)}]) assert.throws(()=>validateLibraryArticle({...valid,...changes}));
});
test("library article RLS restricts all browser CRUD to its owner",()=>{
 const sql=readFileSync("supabase/migrations/20261015000000_library_articles.sql","utf8");
 assert.match(sql,/enable row level security/);
 assert.match(sql,/using \(auth.uid\(\) = user_id\) with check \(auth.uid\(\) = user_id\)/);
 assert.match(sql,/revoke all.*from anon/);
 const soft=readFileSync("supabase/migrations/20261124000000_library_articles_soft_delete.sql","utf8");
 assert.match(soft,/deleted_at timestamptz/);
 assert.doesNotMatch(soft,/delete from public.library_articles/);
});
test("editing merges into the same article and leaves unread fields alone",()=>{
 const current={id:"keep-id",source_url:"https://example.com/read",title:"Old",body_en:"First.",author:"Ann",outlet:"Mag",level:"B2",summary_zh:"简介",analysis:{key_vocab:[{en:"keep"}]},favorited:true,folder:"folder_1",read_at:"2026-11-01T00:00:00.000Z",user_id:"user-1"};
 const merged=mergeLibraryArticleUpdate(current,{title:" New title ",body_en:"First.\n\nSecond."});
 assert.equal(merged.id,"keep-id");
 assert.equal(merged.title,"New title");
 assert.equal(merged.author,"Ann");
 assert.deepEqual(merged.analysis,{key_vocab:[{en:"keep"}]});
 assert.equal(merged.favorited,undefined);
 assert.equal(merged.folder,undefined);
 assert.equal(merged.read_at,undefined);
});
test("reader, list and importer expose edit, recycle and restore without a second insert path",()=>{
 const list=readFileSync("src/components/study/LibraryArticleList.jsx","utf8");
 const reader=readFileSync("src/pages/DailyArticleReader.jsx","utf8");
 const importer=readFileSync("src/components/study/ArticleLinkImporter.jsx","utf8");
 const api=readFileSync("src/lib/libraryArticles.js","utf8");
 assert.match(list,/编辑/);
 assert.match(list,/删除/);
 assert.match(list,/回收站/);
 assert.match(list,/softDeleteLibraryArticles/);
 assert.match(list,/restoreLibraryArticles/);
 assert.match(list,/删除所选/);
 assert.match(reader,/编辑/);
 assert.match(reader,/删除/);
 assert.match(reader,/英文原文/);
 assert.match(reader,/答案解析与本课易错点/);
 assert.match(reader,/ArticleQuestionTable/);
 assert.doesNotMatch(reader,/暂无解析/);
 assert.match(importer,/updateLibraryArticle/);
 assert.match(importer,/ArticleAnalysisEditor/);
 assert.match(api,/insert\(/);
 assert.equal((api.match(/\.insert\(/g)||[]).length,1);
 assert.match(api,/\.is\("deleted_at", null\)/);
});
