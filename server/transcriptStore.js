// Shared, user-independent transcript cache in Supabase (public.transcript_cache).
// Only the service role reads/writes it (from /api/youtube-transcript and the
// recommendations import). Every failure (not configured, table not migrated,
// network) degrades to "no cache" so transcript fetching is never blocked.
import { createClient } from "@supabase/supabase-js";

function defaultSupabase(env) {
  const url = String(env.VITE_SUPABASE_URL || env.SUPABASE_URL || "").trim();
  const key = String(env.SUPABASE_SERVICE_ROLE_KEY || "").trim();
  if (!url || !key) return null;
  return createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
}

const STORE_TIMEOUT_MS = 2500;

function withTimeout(promise, ms) {
  let timer;
  return Promise.race([
    promise,
    new Promise((resolve) => { timer = setTimeout(() => resolve(null), ms); }),
  ]).finally(() => clearTimeout(timer));
}

function client(env, createSupabase) {
  try { return (createSupabase || defaultSupabase)(env); } catch { return null; }
}

export async function readSharedTranscript(id, env, { createSupabase, timeoutMs = STORE_TIMEOUT_MS } = {}) {
  const supabase = client(env, createSupabase);
  if (!supabase) return null;
  try {
    const response = await withTimeout(
      supabase.from("transcript_cache").select("youtube_id,title,language,original_language,is_auto_generated,subtitles,extractor").eq("youtube_id", id).maybeSingle(),
      timeoutMs,
    );
    const row = response?.data;
    if (!row || !Array.isArray(row.subtitles) || !row.subtitles.length) return null;
    return {
      videoId: id,
      title: row.title || "",
      language: row.language || "en",
      originalLanguage: row.original_language || row.language || "en",
      isAutoGenerated: Boolean(row.is_auto_generated),
      subtitles: row.subtitles,
      extractor: `supabase-cache:${row.extractor || "unknown"}`,
      diagnostics: [],
      attempt: 0,
    };
  } catch {
    return null;
  }
}

export async function writeSharedTranscript(id, result, env, { createSupabase, timeoutMs = STORE_TIMEOUT_MS } = {}) {
  if (!result?.subtitles?.length || result.translated) return false;
  const supabase = client(env, createSupabase);
  if (!supabase) return false;
  try {
    const response = await withTimeout(supabase.from("transcript_cache").upsert({
      youtube_id: id,
      title: result.title || "",
      language: result.language || "en",
      original_language: result.originalLanguage || result.language || "en",
      is_auto_generated: Boolean(result.isAutoGenerated),
      subtitles: result.subtitles.map(({ text, start, duration }) => ({ text, start, duration })),
      extractor: result.extractor || "",
      updated_at: new Date().toISOString(),
    }, { onConflict: "youtube_id" }), timeoutMs);
    return Boolean(response && !response.error);
  } catch {
    return false;
  }
}
